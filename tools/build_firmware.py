def build(out_path=None):
    os.makedirs(GEN, exist_ok=True)
    for name, text in (("jumptable.inc", gen_jumptable()), ("keymap.inc", gen_keymap()),
                       ("asmtab.inc", gen_asmtab())):
        with open(os.path.join(GEN, name), "w") as f:
            f.write(text)
    main = os.path.join(FW, "main.asm")
    a = asm.Assembler(origin=0)
    image = a.assemble(open(main).read(), main)
    if image is None:
        raise SystemExit("\n".join(str(e) for e in a.errors[:20]))
    for i, name in enumerate(asm.RUNTIME):
        assert a.symbols[name] == asm.PREDEFINED[name], name
    fixed_end = a.symbols["FIXED_END"]
    tab_end = a.symbols["ASMTAB_END"]
    if fixed_end > 0x4000:
        raise SystemExit("fixed firmware too large: ends at $%04X" % fixed_end)
    if tab_end > 0x5000:
        raise SystemExit("assembler tables too large")
    flash = bytearray(b"\xff" * (32 * PAGE))
    for addr, b in image.items():
        if addr < 0x4000:
            flash[addr] = b
        elif addr < 0x5000:
            flash[BANK_ASMTAB * PAGE + addr - 0x4000] = b
        else:
            raise SystemExit("firmware byte outside ROM at $%04X" % addr)
    flash[BANK_FONT * PAGE:(BANK_FONT + 1) * PAGE] = font.build_font()
    pages = help_pages()
    help_bytes = bytes([len(pages)]) + "\f".join(pages).encode("ascii") + b"\0"
    assert len(help_bytes) <= HELP_PAGES * PAGE, len(help_bytes)
    flash[BANK_HELP * PAGE:BANK_HELP * PAGE + len(help_bytes)] = help_bytes
    directory = bytearray([len(EXAMPLES)])
    page = BANK_EXDIR + 1
    for title, fname in EXAMPLES:
        text = example_text(fname).encode("ascii") + b"\0"
        assert len(text) < 16 * 1024 - 64, "%s too large for the editor buffer" % fname
        directory += title.encode("ascii") + b"\0" + bytes([page])
        flash[page * PAGE:page * PAGE + len(text)] = text
        page += (len(text) + PAGE - 1) // PAGE
        assert page <= 32, "examples do not fit in flash"
    flash[BANK_EXDIR * PAGE:BANK_EXDIR * PAGE + len(directory)] = directory
    out_path = out_path or os.path.join(ROOT, "build", "rom", "firmware.bin")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "wb") as f:
        f.write(flash)
    stats = {"fixed_bytes": fixed_end, "asmtab_bytes": tab_end - 0x4000,
             "help_bytes": len(help_bytes), "help_pages": len(pages),
             "examples": len(EXAMPLES), "last_page": page - 1}
    return bytes(flash), a, stats


if __name__ == "__main__":
    flash, a, st = build(sys.argv[1] if len(sys.argv) > 1 else None)
    print("firmware.bin: fixed code %d of 16384 bytes (%.0f%%), assembler tables %d bytes,"
          " help %d pages (%d bytes), %d examples, flash pages used 0-%d"
          % (st["fixed_bytes"], 100.0 * st["fixed_bytes"] / 16384, st["asmtab_bytes"],
             st["help_pages"], st["help_bytes"], st["examples"], st["last_page"]))
