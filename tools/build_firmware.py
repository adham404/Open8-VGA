"""Build the Open8-VGA boot firmware flash image (SST39SF010A, 128 KiB).

Generates firmware/gen/*.inc from the single sources of truth (isa.py, asm.py, ps2.py),
assembles firmware/main.asm, adds font, help pages and example programs, and writes
build/rom/firmware.bin.  Author: Adham Elshafei
"""
import os
import sys

import asm
import font
import isa
import ps2

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FW = os.path.join(ROOT, "firmware")
GEN = os.path.join(FW, "gen")
PAGE = 4096
BANK_FONT, BANK_HELP, BANK_ASMTAB, BANK_EXDIR = 4, 5, 12, 13
HELP_PAGES = 3
EXAMPLES = [("Hello world", "01_hello.asm"), ("Arithmetic", "02_arith.asm"),
            ("Counting loop", "03_loop.asm"), ("Decisions (branching)", "04_branch.asm"),
            ("Keyboard input", "05_keys.asm"), ("Bouncing ball (graphics)", "06_bounce.asm"),
            ("TETRIS", "07_tetris.asm"), ("OPEN8 RUNNER (scrolling platformer)", "08_platformer.asm")]

KIND = {"A": 1, "B": 2, "X": 3, "SP": 4, "XL": 5, "XH": 6, "imm8": 7, "imm16": 7,
        "abs": 8, "ind": 9, "indinc": 10, "addr": 11}
DIRECTIVES = [(".DB", 1), (".BYTE", 1), (".DW", 2), (".WORD", 2), (".DS", 3), (".RES", 3),
              (".ORG", 4)]


def db(values, per_line=16):
    out = []
    for i in range(0, len(values), per_line):
        out.append("        .db " + ", ".join("$%02X" % v for v in values[i:i + per_line]))
    return "\n".join(out)


NAME_MAX = 14       # must match firmware/vars.inc


def name14(s):
    b = s.upper().encode()
    assert len(b) <= NAME_MAX, s
    return list(b) + [0] * (NAME_MAX - len(b))


def gen_jumptable():
    lines = ["; generated by tools/build_firmware.py - runtime entry points"]
    for i, name in enumerate(asm.RUNTIME):
        lines.append("%-8s JMP r_%s   ; $%04X" % (name + ":", name.lower(), 3 + 3 * i))
    return "\n".join(lines) + "\n"


def gen_keymap():
    plain = [0] * 128
    shifted = [0] * 128
    for ch, code in ps2.KEYS.items():
        plain[code] = ord(ch)
        shifted[code] = ord(ch.upper()) if ch.isalpha() else ord(ch)
    for sym, base in ps2.SHIFTED.items():
        shifted[ps2.KEYS[base]] = ord(sym)
    specials = {"ESC": 27}
    specials.update({"F%d" % i: 0x8F + i for i in range(1, 13)})
    for name, key in specials.items():
        code = ps2.SPECIAL[name]
        code = 0x02 if code == 0x83 else code         # F7 remapped by the driver
        plain[code] = shifted[code] = key
    ext = []
    short = {"DELETE": "DEL", "INSERT": "INS"}
    for name, code in ps2.EXTENDED.items():
        if name in ("RCTRL", "RALT"):
            continue                                  # modifiers, handled by the driver
        key = asm.KEYCODES["K_" + short.get(name, name)]
        ext += [code, key]
    return ("; generated by tools/build_firmware.py - PS/2 set 2 -> key codes\n"
            "keymap_plain:\n" + db(plain) + "\nkeymap_shift:\n" + db(shifted) +
            "\nkeymap_ext:\n" + db(ext + [0]) + "\n")


def gen_asmtab():
    out = ["; generated by tools/build_firmware.py - tables for the on-board assembler",
           "isa_tab:              ; mnemonic(5) kinds(k1|k2<<4) operand-bytes opcode"]
    for ins in isa.INSTRS:
        mn = list(ins.mnem.ljust(5).encode())
        ks = [KIND[o] for o in ins.operands] + [0, 0]
        out.append(db(mn + [ks[0] | ks[1] << 4, ins.size - 1, ins.opcode]) +
                   "   ; " + ins.syntax())
    out.append("        .db 0")
    out.append("alias_tab:")
    for a, target in asm.ALIASES.items():
        out.append(db(list(a.ljust(5).encode()) + list(target.ljust(5).encode())))
    out.append("        .db 0")
    out.append("dir_tab:")
    for name, code in DIRECTIVES:
        out.append(db(name14(name) + [code]))
    out.append("        .db 0")
    out.append("predef_tab:")
    for name, value in sorted(asm.PREDEFINED.items()):
        out.append(db(name14(name) + [value & 0xFF, value >> 8]) + "   ; " + name)
    out.append("        .db 0")
    out.append("slot_tab:")
    for start in range(0, 192, 32):
        out.append("        .dw " + ", ".join("SYMTAB + %d" % (i * 16) for i in range(start, start + 32)))
    return "\n".join(out) + "\n"


def unexpand(text):
    """Replace runs of spaces that end on a tab stop by TAB characters (outside strings).
    The editor shows TABs as spaces up to the next multiple of 8, so the text looks the
    same but takes less of the 16 KB buffer. Checked: expands back to the original."""
    out = []
    for line in text.split("\n"):
        res, col, pend, quote = "", 0, 0, False
        for ch in line:
            if ch == '"':
                quote = not quote
            if ch == " " and not quote:
                pend += 1
                col += 1
                if col % 8 == 0:                    # a tab stop: close the run
                    res += "\t" if pend > 1 else " "
                    pend = 0
                continue
            res += " " * pend + ch
            pend = 0
            col += 1
        res += " " * pend
        assert res.expandtabs(8) == line, line
        out.append(res)
    return "\n".join(out)


def example_text(fname):
    """Example source exactly as stored in ROM (TAB-compressed)."""
    return unexpand(open(os.path.join(ROOT, "examples", fname)).read())


