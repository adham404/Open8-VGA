def glyph_from_5x7(spec):
    rows = [int(r, 2) for r in spec.split()]
    assert len(rows) == 7
    cell = [0]
    for r in rows:
        b = r << 2                     # 5 pixels in bits 6..2 -> columns 1..5
        cell += [b, b]
    cell += [0]
    return cell


def build_font():
    img = bytearray(4096)
    for c in range(128):
        if c in TILES:
            rows = TILES[c]
        elif 32 <= c <= 126:
            rows = glyph_from_5x7(ASCII_5X7[chr(c)])
        else:
            rows = [0] * 16
        assert len(rows) == 16, c
        for y, b in enumerate(rows):
            img[c * 16 + y] = b & 0xFF
            img[(c + 128) * 16 + y] = ~b & 0xFF
    return bytes(img)


def main(path):
    with open(path, "wb") as f:
        f.write(build_font())
    print("wrote", path, "4096 bytes")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/rom/font.bin")
