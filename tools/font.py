def tile(rows):
    """8x16 tile from 16 strings of 8 chars ('#' or 'X' = on)."""
    assert len(rows) == 16, len(rows)
    out = []
    for r in rows:
        assert len(r) == 8, r
        out.append(int("".join("1" if ch in "#X" else "0" for ch in r), 2))
    return out


def box(up, down, left, right):
    rows = []
    for y in range(16):
        b = 0
        if (up and y <= 8) or (down and y >= 7):
            b |= 0b00011000
        if y in (7, 8):
            if left: b |= 0b11111000
            if right: b |= 0b00011111
            if left or right: b |= 0b00011000
        rows.append(b)
    return rows


